"""Write the golden fixture that the demo's TypeScript engine port is tested against (M5).

For two tiny synthetic markets the script records the Python engine's inputs (latent
qualities, idiosyncratic terms, and every random draw the sequential simulator consumes,
round by round) and its outputs (matchings, exposures, per-round match counts, slate counts,
DA_A matching and metrics). The vitest ``demo/src/engine.test.ts`` feeds the same inputs to
the port and compares the outputs.

The draws are captured by replaying, on fresh generators built from the same SeedSequences,
exactly the calls ``match_lab.sequential.simulate_sequential`` makes each round. A wrong
replay would make the port's outcomes differ from the engine's, so the vitest also checks
the replay. Compute: well under a second.

Usage: ``.venv/bin/python scripts/make_sandbox_fixture.py``.
"""

from __future__ import annotations

import json
from pathlib import Path

import numpy as np

from match_lab.market import MarketParams, build_market
from match_lab.matching import da_a
from match_lab.metrics import compute_metrics
from match_lab.sequential import Policy, SequentialSeeds, SequentialSettings, simulate_sequential

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "demo" / "src" / "fixtures" / "engine_fixture.json"
METRICS = ("W", "W_A", "W_B", "U", "M", "n_matched", "blocking_pairs", "blocking_per_100",
           "gini_exposure_A", "gini_exposure_B")

CASES = [
    {"name": "imbalanced", "seed": 20261125, "n_a": 8, "r": 1.5, "rho": 0.5, "theta": 0.5, "T": 6, "k": 3},
    {"name": "balanced-correlated", "seed": 7, "n_a": 7, "r": 1.0, "rho": 0.9, "theta": 0.3, "T": 5, "k": 2},
]


def _metrics(market, ma, mb, ea=None, eb=None) -> dict:
    m = compute_metrics(market, ma, mb, ea, eb)
    return {k: m[k] for k in METRICS}


def make_case(c: dict) -> dict:
    params = MarketParams(n_a=c["n_a"], r=c["r"], rho=c["rho"], theta=c["theta"])
    n_a, n_b = params.n_a, params.n_b
    root = np.random.SeedSequence(c["seed"])
    market_seed, seq_parent = root.spawn(2)
    rng = np.random.default_rng(market_seed)
    q_a, q_b = rng.standard_normal(n_a), rng.standard_normal(n_b)
    e_a, e_b = rng.standard_normal((n_a, n_b)), rng.standard_normal((n_b, n_a))
    a, b = np.sqrt(params.rho), np.sqrt(1.0 - params.rho)
    u_a = a * q_b[None, :] + b * e_a
    u_b = a * q_a[None, :] + b * e_b
    market = build_market(params, q_a, q_b, u_a, u_b)
    seeds = SequentialSeeds.from_parent(seq_parent)

    # Replay the per-round draws in the engine's order.
    order_rng = np.random.default_rng(seeds.viewer_order)
    key_rng = np.random.default_rng(seeds.slate_keys)
    tie_rng = np.random.default_rng(seeds.tie_keys)
    rounds = []
    for _ in range(c["T"]):
        perm = order_rng.permutation(n_a + n_b)
        rk = (key_rng.random((n_a, n_b)), key_rng.random((n_b, n_a)))
        tk = (tie_rng.random(n_a), tie_rng.random(n_b))
        tie_rng.random((n_a, n_b)), tie_rng.random((n_b, n_a))  # per-viewer keys, unused with tie_scope="global"
        rounds.append({"perm": perm.tolist(), "rand_a": rk[0].tolist(), "rand_b": rk[1].tolist(),
                       "tie_a": tk[0].tolist(), "tie_b": tk[1].tolist()})

    settings = SequentialSettings(T=c["T"], k=c["k"], delta=0.5, tie_scope="global")
    outcomes = {}
    for pol in Policy:
        out = simulate_sequential(market, pol, settings, seeds)
        outcomes[pol.value] = {
            "match_a": out.match_a.tolist(), "match_b": out.match_b.tolist(),
            "exposure_a": out.exposure_a.tolist(), "exposure_b": out.exposure_b.tolist(),
            "n_slates": out.n_slates, "short_slates": out.short_slates,
            "cap_short_slates": out.cap_short_slates, "matches_by_round": out.matches_by_round,
            "metrics": _metrics(market, out.match_a, out.match_b, out.exposure_a, out.exposure_b),
        }
    ma, mb = da_a(market)
    outcomes["DA_A"] = {"match_a": ma.tolist(), "match_b": mb.tolist(), "metrics": _metrics(market, ma, mb)}
    return {
        "case": c,
        "n_b": n_b,
        "q_a": q_a.tolist(), "q_b": q_b.tolist(), "e_a": e_a.tolist(), "e_b": e_b.tolist(),
        "sat_a": market.sat_a.tolist(), "acc_a": market.acc_a.astype(int).tolist(),
        "sat_b": market.sat_b.tolist(), "acc_b": market.acc_b.astype(int).tolist(),
        "rounds": rounds,
        "outcomes": outcomes,
    }


def main() -> None:
    doc = {
        "note": "Golden fixture from the Python engine (match_lab); generated by scripts/make_sandbox_fixture.py. Synthetic.",
        "cases": [make_case(c) for c in CASES],
    }
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(json.dumps(doc, separators=(",", ":"), allow_nan=False) + "\n", encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)} ({OUT.stat().st_size} bytes)")


if __name__ == "__main__":
    main()
